import json
import re
import urllib.request
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

# Pinned icon set version: icons are copied into the app, so they never change on their own.
SOLAR_VERSION = "1.2.13"
SOLAR_URL = f"https://cdn.jsdelivr.net/npm/@iconify-json/solar@{SOLAR_VERSION}/icons.json"
OUTPUT = settings.APPS_DIR / "static" / "js" / "icons.js"
SOURCES = ("*.html", "*.py", "*.js")
ICON_NAME = re.compile(r"solar:([a-z0-9-]+)")


class Command(BaseCommand):
    help = (
        "Bundle the Solar icons the app uses into static/js/icons.js, so pages show icons "
        "without asking the Iconify API on the internet. Run it after using a new icon; "
        "icons missing from the bundle still load from the API."
    )

    def handle(self, **options):
        names = self.used_icons()
        try:
            with urllib.request.urlopen(SOLAR_URL, timeout=60) as response:  # noqa: S310 (fixed https URL)
                icon_set = json.load(response)
        except OSError as error:
            raise CommandError(f"Couldn't download the Solar icon set: {error}") from error

        icons, all_aliases = icon_set["icons"], icon_set.get("aliases", {})
        missing = sorted(names - icons.keys() - all_aliases.keys())
        aliases = {name: all_aliases[name] for name in sorted(names & all_aliases.keys())}
        # An alias points at another icon (its "parent"), which must be in the bundle too.
        wanted = (names & icons.keys()) | {alias["parent"] for alias in aliases.values()}
        bundle = {
            "prefix": "solar",
            "width": icon_set.get("width", 24),
            "height": icon_set.get("height", 24),
            "icons": {name: icons[name] for name in sorted(wanted)},
            "aliases": aliases,
        }
        OUTPUT.write_text(
            "// Generated by `python manage.py build_icons` from @iconify-json/solar "
            f"{SOLAR_VERSION}; do not edit.\n"
            "// The icons the app uses, loaded before the iconify-icon component so it needs no API calls.\n"
            f"window.IconifyPreload = [{json.dumps(bundle, separators=(',', ':'), sort_keys=True)}];\n",
            encoding="utf-8",
        )
        for name in missing:
            self.stdout.write(self.style.WARNING(f"Not in the Solar set: solar:{name}"))
        self.stdout.write(self.style.SUCCESS(f"{len(bundle['icons'])} icons written to {OUTPUT.name}."))

    def used_icons(self) -> set[str]:
        names = set()
        for pattern in SOURCES:
            for path in Path(settings.APPS_DIR).rglob(pattern):
                if "matdash" in path.parts or path == OUTPUT:
                    continue
                names |= set(ICON_NAME.findall(path.read_text(encoding="utf-8", errors="ignore")))
        return names
